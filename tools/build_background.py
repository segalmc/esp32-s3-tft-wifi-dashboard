#!/usr/bin/env python3
"""Build the 320x480 RGB565 dashboard backdrop from a licensed photograph."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageOps


WIDTH, HEIGHT = 320, 480
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "assets/source/mountain_sunset_over_lake.jpg"
DEFAULT_OUTPUT = ROOT / "src/BackgroundAsset.cpp"


def crop_photo(source: Image.Image) -> Image.Image:
    # Bias the crop slightly upward so the peak, shore, and reflection survive.
    return ImageOps.fit(source.convert("RGB"), (WIDTH, HEIGHT),
                        method=Image.LANCZOS, centering=(0.50, 0.46))


def compose(image: Image.Image) -> Image.Image:
    overlay = Image.new("RGBA", (WIDTH, HEIGHT), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    draw.rounded_rectangle((12, 12, 307, 77), radius=14, fill=(7, 24, 42, 206),
                           outline=(115, 196, 196, 90), width=1)
    draw.rounded_rectangle((12, 398, 307, 467), radius=14, fill=(7, 24, 42, 100))
    # Four rows of paired glass cards. Their inside pixels are retained in
    # flash, so updating text restores the exact photograph and tint.
    for row in range(4):
        y = 188 + row * 67
        for x in (12, 165):
            draw.rounded_rectangle((x, y, x + 143, y + 58), radius=12,
                                   fill=(6, 23, 41, 214),
                                   outline=(135, 213, 216, 95), width=1)
            draw.line((x + 13, y + 13, x + 30, y + 13),
                      fill=(68, 219, 207, 220), width=2)
    # A tiny warm accent echoes the mountain light without implying weather.
    draw.rounded_rectangle((270, 27, 293, 32), radius=2,
                           fill=(255, 165, 98, 240))
    return Image.alpha_composite(image.convert("RGBA"), overlay).convert("RGB")


def rgb565_words(image: Image.Image) -> list[int]:
    pixels = list(image.getdata())
    return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            for r, g, b in pixels]


def write_array(file, name: str, image: Image.Image) -> None:
    words = rgb565_words(image)
    file.write(f'const uint32_t k{name}Checksum = 0x{sum(words) & 0xFFFFFFFF:08X};\n')
    file.write(f'alignas(4) const uint16_t k{name}Pixels[320 * 480] PROGMEM = {{\n')
    for index in range(0, len(words), 16):
        file.write('  ' + ', '.join(f'0x{word:04X}' for word in words[index:index + 16]) + ',\n')
    file.write('};\n')


def write_cpp(image: Image.Image, photo: Image.Image, output: Path) -> None:
    with output.open("w", encoding="ascii") as file:
        file.write('// Generated by tools/build_background.py; do not edit.\n')
        file.write('#include "BackgroundAsset.h"\n\n#if TFT_HARDWARE_ENABLED\n')
        write_array(file, 'Background', image)
        write_array(file, 'PhotoOnly', photo)
        file.write('#endif\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT,
                        help="licensed source photograph")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--preview", type=Path,
                        help="optional 320x480 PNG preview")
    args = parser.parse_args()
    with Image.open(args.input) as source:
        photo = crop_photo(source)
    image = compose(photo)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    write_cpp(image, photo, args.output)
    if args.preview:
        image.save(args.preview)
    print(f"Wrote {args.output}: {WIDTH}x{HEIGHT}, {WIDTH * HEIGHT * 2} RGB565 bytes")


if __name__ == "__main__":
    main()
